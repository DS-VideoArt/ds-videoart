FONTS = '<link href="https://fonts.googleapis.com/css2?family=Frank+Ruhl+Libre:wght@500;700;900&family=Heebo:wght@400;500;600;700;800;900&display=swap" rel="stylesheet">'


def apply(page, current, solid):
    path = os.path.join(ROOT, page)
    s = open(path, encoding="utf-8").read()
    head = head_html(current, solid)
    if "<!-- site-head" in s:
        s = re.sub(r"<!-- site-head.*?<!-- /site-head -->", lambda m: head, s, count=1, flags=re.S)
    else:
        s, n = re.subn(r'<nav class="nav[^"]*"[^>]*>.*?</nav>\s*<div class="mobile-menu"[^>]*>.*?</div>', lambda m: head, s, count=1, flags=re.S)
        if n != 1: sys.exit(f"{page}: classic header not found")
    foot = FOOT_SHORT if page in SHORT_FOOT_PAGES else FOOT
    if "<!-- site-foot" in s:
        s = re.sub(r"<!-- site-foot.*?<!-- /site-foot -->", lambda m: foot, s, count=1, flags=re.S)
    else:
        s, n = re.subn(r'<footer class="footer">.*?</footer>', lambda m: foot, s, count=1, flags=re.S)
        if n != 1: sys.exit(f"{page}: classic footer not found")
    # design layer: display font, stylesheet after the last one, the js class, the behaviour script
    s = re.sub(r'<link href="https://fonts\.googleapis\.com/css2\?family=[^"]*" rel="stylesheet">', FONTS, s, count=1)
    if "studio.css" not in s:
        last = list(re.finditer(r'<link rel="stylesheet" href="[^"]*">', s))[-1]
        s = s[:last.end()] + f'\n  <link rel="stylesheet" href="/studio.css?v={VERSION}">' + s[last.end():]
    s = re.sub(r'/studio\.css\?v=\d+[a-z]?', f"/studio.css?v={VERSION}", s)
    if 'classList.add("js")' not in s:
        s = s.replace("</head>", '  <script>document.documentElement.classList.add("js")</script>\n</head>', 1)
    if "studio.js" not in s:
        m = re.search(r'\n\s*<script src="[^"]*search\.js[^"]*"[^>]*></script>', s)
        if not m: sys.exit(f"{page}: search.js tag not found")
        s = s[:m.start()] + f'\n  <script src="/studio.js?v={VERSION}"></script>' + s[m.start():]
    s = re.sub(r'/studio\.js\?v=\d+[a-z]?', f"/studio.js?v={VERSION}", s)
    s = re.sub(r'<meta name="theme-color" content="[^"]*">', '<meta name="theme-color" content="#0b1426">', s, count=1)
    open(path, "w", encoding="utf-8").write(s)


